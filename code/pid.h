//-------------------------------------------------------------------------------------------------------------------
// 函数简介     转向内环（陀螺仪）PID控制
// 参数说明     Gyro: 实际角速度值
//              Gyro_qiwang: 期望角速度值
// 返回参数     PID计算后的PWM输出值
// 使用示例     float pwm = CascadePID_Turn_Gyro(gyro_value, 50.0);
// 备注信息     位置式PD控制
//-------------------------------------------------------------------------------------------------------------------
float CascadePID_Turn_Gyro(float Gyro, float Gyro_qiwang);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     转向外环（角度）PID控制
// 参数说明     angle: 实际角度值
// 返回参数     PID计算后的PWM输出值
// 使用示例     float pwm = CascadePID_Turn_Angle(angle_value);
// 备注信息     位置式PD控制，根据不同场景动态调整kp和kd
//-------------------------------------------------------------------------------------------------------------------
float CascadePID_Turn_Angle(float angle);

