// 函数简介     横滚角PID控制
// 参数说明     angle: 实际横滚角
//              angle_qiwang: 期望横滚角
// 返回参数     PID计算后的PWM输出值
// 使用示例     float pwm = CascadePID_Rolling_Angle(roll_angle, 0.0);
// 备注信息     增量式PID控制
//-------------------------------------------------------------------------------------------------------------------
float CascadePID_Rolling_Angle(float angle, float angle_qiwang);

